#!/usr/bin/env bash
# villa's own seed-heading and resume tests for repro/fibers/villa_volume_seed_heading_eab6108b9.patch, at a villa
# commit whose tracer imports the native vc_reader and vc_object_store, on a host where neither is built.
# repro/fibers/stub_native_villa.py stands in for both: any name imported from them is a dummy. The two new test files
# replace every call they reach, so their outcomes are the patch's; tests that need the real readers fail on both
# sides alike. This is NOT integration evidence: villa's tests with the real builds, and the GPU re-run, still are.
#
#   VILLA=<villa clone> PY=<python with torch> [PYTEST_SITE=<dir holding pytest>] OUT=<record> \
#     repro/fibers/run_villa_seed_heading_tests_stubbed.sh
set -euo pipefail
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
VILLA="${VILLA:?a villa clone holding REF}"
PY="${PY:?a Python with torch, numpy and scipy}"
OUT="${OUT:?the record to write}"
REF="${REF:-eab6108b948d5cb622b25ac87c9b32d5664a1504}"
PATCH="$REPO/repro/fibers/villa_volume_seed_heading_eab6108b9.patch"
TESTS=src/vesuvius/neural_tracing/tracers/fibers/tests
NEW="$TESTS/test_volume_seed_heading.py $TESTS/test_volume_seed_resume.py"
OTHER="$TESTS/test_volume_performance.py $TESTS/test_volume_seeding.py $TESTS/test_volume_policy.py"
W="$(mktemp -d)"
mkdir -p "$W/before" "$W/after" "$W/plugin"
cp "$REPO/repro/fibers/stub_native_villa.py" "$W/plugin/"
git -C "$VILLA" archive "$REF" vesuvius | tar -x -C "$W/before"
git -C "$VILLA" archive "$REF" vesuvius | tar -x -C "$W/after"
(cd "$W/after" && git apply "$PATCH")
# before: villa's code as at REF, with the patch's two new test files beside it
cp "$W/after/vesuvius/$TESTS/test_volume_seed_heading.py" "$W/after/vesuvius/$TESTS/test_volume_seed_resume.py" \
  "$W/before/vesuvius/$TESTS/"
run() {  # side, test files
  (cd "$W/$1/vesuvius" && PYTHONPATH="$W/$1/vesuvius/src:$W/plugin${PYTEST_SITE:+:$PYTEST_SITE}" CUDA_VISIBLE_DEVICES= \
    "$PY" -m pytest -q -p no:cacheprovider -p stub_native_villa -rfEs $2 2>&1 \
    | grep -E '^(FAILED|ERROR|SKIPPED)|[0-9]+ (passed|failed)' | sed 's/ - .*//' | sort) || true
}
{
  echo "# villa's seed-heading tests, native vc_reader/vc_object_store STUBBED (repro/fibers/stub_native_villa.py)"
  echo "# generated by repro/fibers/run_villa_seed_heading_tests_stubbed.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "villa $(git -C "$VILLA" rev-parse "$REF") ($(git -C "$VILLA" show -s --format=%cI "$REF"))"
  echo "patch sha256 $(sha256sum "$PATCH" | cut -d' ' -f1)"
  "$PY" -c 'import sys, numpy, torch; print("Python", sys.version.split()[0], "numpy", numpy.__version__, "torch", torch.__version__)'
  for side in before after; do
    echo "== $side: the new tests"
    run "$side" "$NEW"
    echo "== $side: villa's other volume tests"
    run "$side" "$OTHER"
  done
} > "$OUT"
echo "wrote $OUT"
